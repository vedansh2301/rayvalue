// Generates src/lib/brand/country-outlines.ts from Natural Earth 1:110m admin-0 countries (public domain,
// https://www.naturalearthdata.com/). Usage: node scripts/gen-country-outlines.mjs path/to/ne_110m_admin_0_countries.geojson
// Each country becomes one simplified SVG path in a box at most 100 units on its longest side (equirectangular with
// cos(latitude) correction). Overseas pieces (Alaska, Hawaii, French Guiana, ...) are dropped so the shape is the home territory.
import { readFileSync, writeFileSync } from 'node:fs';

const input = process.argv[2];
if (!input) { console.error('usage: node scripts/gen-country-outlines.mjs <geojson>'); process.exit(1); }
const SEGMENTS = {
  GBR: 'uk', IRL: 'ie', DEU: 'de', AUT: 'at', CHE: 'ch', FRA: 'fr', BEL: 'be', NLD: 'nl', ESP: 'es', PRT: 'pt', ITA: 'it',
  SWE: 'se', DNK: 'dk', NOR: 'no', FIN: 'fi', POL: 'pl', CZE: 'cz', ROU: 'ro', USA: 'us', CAN: 'ca', BRA: 'br', CHL: 'cl',
  COL: 'co', ARG: 'ar', PER: 'pe', DOM: 'do', JAM: 'jm', AUS: 'au', JPN: 'jp', IND: 'in', ZAF: 'za', ISR: 'il',
};
const gj = JSON.parse(readFileSync(input, 'utf8'));
const area = (r) => Math.abs(r.reduce((s, p, i) => { const q = r[(i + 1) % r.length]; return s + (p[0] * q[1] - q[0] * p[1]); }, 0) / 2);
const centroid = (r) => [r.reduce((s, p) => s + p[0], 0) / r.length, r.reduce((s, p) => s + p[1], 0) / r.length];
function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts[pts.length - 1]];
  let idx = 0, max = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const [x, y] = pts[i];
    const dx = b[0] - a[0], dy = b[1] - a[1];
    const len = Math.hypot(dx, dy) || 1e-9;
    const d = Math.abs(dy * x - dx * y + b[0] * a[1] - b[1] * a[0]) / len;
    if (d > max) { max = d; idx = i; }
  }
  if (max <= tol) return [a, b];
  return [...dp(pts.slice(0, idx + 1), tol).slice(0, -1), ...dp(pts.slice(idx), tol)];
}
const out = {};
for (const f of gj.features) {
  const seg = SEGMENTS[f.properties.ADM0_A3] ?? SEGMENTS[f.properties.ISO_A3_EH];
  if (!seg || out[seg]) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = polys.map((p) => p[0]);
  const biggest = rings.reduce((a, b) => (area(b) > area(a) ? b : a));
  const c0 = centroid(biggest);
  const keep = rings.filter((r) => area(r) >= area(biggest) * 0.015 && Math.abs(centroid(r)[0] - c0[0]) < 30 && Math.abs(centroid(r)[1] - c0[1]) < 30);
  const lat0 = c0[1];
  const k = Math.cos((lat0 * Math.PI) / 180);
  const proj = keep.map((r) => r.map(([lon, lat]) => [lon * k, -lat]));
  const xs = proj.flat().map((p) => p[0]), ys = proj.flat().map((p) => p[1]);
  const [x0, x1, y0, y1] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
  const scale = 100 / Math.max(x1 - x0, y1 - y0);
  const d = proj.map((r) => {
    const all = r.map(([x, y]) => [(x - x0) * scale, (y - y0) * scale]);
    // A closed ring has first == last, so split it at the point farthest from the start and simplify the two halves.
    let far = 1;
    for (let i = 1; i < all.length; i++) if (Math.hypot(all[i][0] - all[0][0], all[i][1] - all[0][1]) > Math.hypot(all[far][0] - all[0][0], all[far][1] - all[0][1])) far = i;
    const pts = [...dp(all.slice(0, far + 1), 0.45).slice(0, -1), ...dp(all.slice(far), 0.45)];
    if (pts.length < 4) return '';
    return 'M' + pts.map(([x, y]) => `${Math.round(x * 10) / 10} ${Math.round(y * 10) / 10}`).join('L') + 'Z';
  }).join('');
  out[seg] = { w: Math.round((x1 - x0) * scale * 10) / 10, h: Math.round((y1 - y0) * scale * 10) / 10, d };
}
const missing = Object.values(SEGMENTS).filter((s) => !out[s]);
if (missing.length) console.warn('missing:', missing.join(','));
const body = Object.keys(out).sort().map((k) => `  ${k}: { w: ${out[k].w}, h: ${out[k].h}, d: '${out[k].d}' },`).join('\n');
writeFileSync('src/lib/brand/country-outlines.ts', `/**
 * Simplified country outlines for the home bento and hubs. GENERATED by scripts/gen-country-outlines.mjs from Natural Earth
 * 1:110m admin-0 countries (public domain, naturalearthdata.com; credited on /credits). Geometry only, no figures.
 * Each shape fits a box of at most 100 units on its longest side: use viewBox="0 0 w h".
 */
export interface CountryOutline { w: number; h: number; d: string }

export const COUNTRY_OUTLINES: Readonly<Record<string, CountryOutline>> = {
${body}
};
`);
console.log('wrote', Object.keys(out).length, 'countries');
